import { createHash, randomUUID } from 'node:crypto';
import { createReadStream } from 'node:fs';
import { mkdir, readdir, stat, unlink, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { Readable } from 'node:stream';
import { DeleteObjectCommand, GetObjectCommand, ListObjectsV2Command, PutObjectCommand, S3Client } from '@aws-sdk/client-s3';
import { AppError } from './errors.js';

/** Allowed upload types, identified by magic bytes — the client-sent mime type is not trusted. */
const SIGNATURES: { mime: string; ext: string; test: (b: Buffer) => boolean }[] = [
  { mime: 'application/pdf', ext: 'pdf', test: (b) => b.subarray(0, 5).toString('latin1') === '%PDF-' },
  { mime: 'image/png', ext: 'png', test: (b) => b.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])) },
  { mime: 'image/jpeg', ext: 'jpg', test: (b) => b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff },
  { mime: 'image/webp', ext: 'webp', test: (b) => b.subarray(0, 4).toString('latin1') === 'RIFF' && b.subarray(8, 12).toString('latin1') === 'WEBP' },
  // ISO base media (MP4/MOV): 'ftyp' box at offset 4 with a known video brand.
  { mime: 'video/mp4', ext: 'mp4', test: (b) => b.subarray(4, 8).toString('latin1') === 'ftyp' && /^(isom|iso2|mp41|mp42|avc1|M4V |qt  )/.test(b.subarray(8, 12).toString('latin1')) },
];

export const IMAGE_TYPES = ['image/png', 'image/jpeg', 'image/webp'];
export const VIDEO_TYPES = ['video/mp4'];
export const DOCUMENT_TYPES = ['application/pdf', ...IMAGE_TYPES];

export function detectFileType(buf: Buffer): { mime: string; ext: string } | null {
  const hit = SIGNATURES.find((s) => s.test(buf));
  return hit ? { mime: hit.mime, ext: hit.ext } : null;
}

export interface StoredFile {
  key: string;
  mime: string;
  size: number;
  sha256: string;
}

/** Keys are generated by the platform; anything else (traversal, absolute paths) is refused. */
function checkKey(key: string) {
  if (!/^[A-Za-z0-9._-]+(\/[A-Za-z0-9._-]+)*$/.test(key) || key.split('/').some((p) => p === '..' || p === '.')) throw new AppError('NOT_FOUND', 404);
}

/**
 * File storage. Uploads are validated here (real type and size) whatever the driver, so the rules
 * cannot differ between development and production.
 */
export abstract class FileStore {
  constructor(protected readonly maxBytes: number, protected readonly maxVideoBytes = maxBytes) {}

  /** Stores a file after checking its real type against `allowed` and its size against the type's limit. */
  async save(prefix: string, buf: Buffer, allowed: string[] = DOCUMENT_TYPES): Promise<StoredFile> {
    const type = detectFileType(buf);
    if (!type || !allowed.includes(type.mime)) throw new AppError('FILE_TYPE_NOT_ALLOWED', 415);
    const limit = VIDEO_TYPES.includes(type.mime) ? this.maxVideoBytes : this.maxBytes;
    if (buf.length > limit) throw new AppError('FILE_TOO_LARGE', 413, { maxBytes: limit });
    const key = `${prefix}/${randomUUID()}.${type.ext}`;
    checkKey(key);
    await this.write(key, buf, type.mime);
    return { key, mime: type.mime, size: buf.length, sha256: createHash('sha256').update(buf).digest('hex') };
  }

  async open(key: string): Promise<{ stream: Readable; size: number }> {
    checkKey(key);
    return this.read(key);
  }

  async remove(key: string): Promise<void> {
    checkKey(key);
    await this.delete(key).catch(() => undefined);
  }

  /** Raw write for restores: the content was validated when it was first uploaded. */
  async put(key: string, buf: Buffer): Promise<void> {
    checkKey(key);
    await this.write(key, buf, detectFileType(buf)?.mime ?? 'application/octet-stream');
  }

  async get(key: string): Promise<Buffer> {
    const { stream } = await this.open(key);
    const chunks: Buffer[] = [];
    for await (const c of stream) chunks.push(c as Buffer);
    return Buffer.concat(chunks);
  }

  /** Every stored key (backups). */
  abstract keys(): AsyncIterable<string>;
  protected abstract write(key: string, buf: Buffer, mime: string): Promise<void>;
  protected abstract read(key: string): Promise<{ stream: Readable; size: number }>;
  protected abstract delete(key: string): Promise<void>;
}

/** Local disk (development, tests, single-server installs with a persistent volume). */
export class LocalStorage extends FileStore {
  constructor(readonly root: string, maxBytes: number, maxVideoBytes = maxBytes) {
    super(maxBytes, maxVideoBytes);
  }

  private resolve(key: string): string {
    const full = path.resolve(this.root, key);
    if (!full.startsWith(path.resolve(this.root) + path.sep)) throw new AppError('NOT_FOUND', 404);
    return full;
  }

  protected async write(key: string, buf: Buffer) {
    const full = this.resolve(key);
    await mkdir(path.dirname(full), { recursive: true });
    await writeFile(full, buf, { flag: 'wx' });
  }

  protected async read(key: string) {
    const full = this.resolve(key);
    const info = await stat(full).catch(() => null);
    if (!info) throw new AppError('NOT_FOUND', 404);
    return { stream: createReadStream(full) as Readable, size: info.size };
  }

  protected async delete(key: string) {
    await unlink(this.resolve(key));
  }

  async *keys(): AsyncIterable<string> {
    const root = path.resolve(this.root);
    const entries = await readdir(root, { withFileTypes: true, recursive: true }).catch(() => []);
    for (const e of entries) if (e.isFile()) yield path.relative(root, path.join(e.parentPath, e.name)).split(path.sep).join('/');
  }
}

export interface S3Options {
  bucket: string; region: string; endpoint?: string | undefined; forcePathStyle: boolean;
  accessKeyId?: string | undefined; secretAccessKey?: string | undefined; prefix?: string | undefined;
}

/**
 * S3-compatible object storage (AWS S3, Cloudflare R2, DigitalOcean Spaces, Wasabi, SeaweedFS, …).
 * The bucket must be private: files are only ever served through the API's permission checks.
 */
export class S3Storage extends FileStore {
  private readonly client: S3Client;
  private readonly prefix: string;

  constructor(private readonly opts: S3Options, maxBytes: number, maxVideoBytes = maxBytes) {
    super(maxBytes, maxVideoBytes);
    this.client = new S3Client({
      region: opts.region, forcePathStyle: opts.forcePathStyle,
      ...(opts.endpoint ? { endpoint: opts.endpoint } : {}),
      // Without explicit keys the SDK's default chain is used (instance role, environment, …).
      ...(opts.accessKeyId && opts.secretAccessKey ? { credentials: { accessKeyId: opts.accessKeyId, secretAccessKey: opts.secretAccessKey } } : {}),
    });
    this.prefix = opts.prefix ? `${opts.prefix.replace(/\/+$/, '')}/` : '';
  }

  protected async write(key: string, buf: Buffer, mime: string) {
    await this.client.send(new PutObjectCommand({ Bucket: this.opts.bucket, Key: this.prefix + key, Body: buf, ContentType: mime, ContentLength: buf.length }));
  }

  protected async read(key: string) {
    try {
      const r = await this.client.send(new GetObjectCommand({ Bucket: this.opts.bucket, Key: this.prefix + key }));
      return { stream: r.Body as Readable, size: Number(r.ContentLength ?? 0) };
    } catch (e) {
      const name = (e as { name?: string }).name;
      if (name === 'NoSuchKey' || name === 'NotFound') throw new AppError('NOT_FOUND', 404);
      throw e;
    }
  }

  protected async delete(key: string) {
    await this.client.send(new DeleteObjectCommand({ Bucket: this.opts.bucket, Key: this.prefix + key }));
  }

  async *keys(): AsyncIterable<string> {
    let token: string | undefined;
    do {
      const r = await this.client.send(new ListObjectsV2Command({ Bucket: this.opts.bucket, Prefix: this.prefix || undefined, ContinuationToken: token }));
      for (const o of r.Contents ?? []) if (o.Key) yield o.Key.slice(this.prefix.length);
      token = r.IsTruncated ? r.NextContinuationToken : undefined;
    } while (token);
  }

  /** Readiness: the bucket is reachable with these credentials. */
  async ping() {
    await this.client.send(new ListObjectsV2Command({ Bucket: this.opts.bucket, MaxKeys: 1 }));
  }
}

export function createStorage(config: {
  STORAGE_DRIVER: 'local' | 's3'; STORAGE_DIR: string; MAX_UPLOAD_BYTES: number; MAX_VIDEO_BYTES: number;
  S3_BUCKET?: string | undefined; S3_REGION: string; S3_ENDPOINT?: string | undefined; S3_FORCE_PATH_STYLE: boolean;
  S3_ACCESS_KEY_ID?: string | undefined; S3_SECRET_ACCESS_KEY?: string | undefined; S3_PREFIX?: string | undefined;
}): FileStore {
  if (config.STORAGE_DRIVER === 's3') {
    return new S3Storage({
      bucket: config.S3_BUCKET!, region: config.S3_REGION, endpoint: config.S3_ENDPOINT, forcePathStyle: config.S3_FORCE_PATH_STYLE,
      accessKeyId: config.S3_ACCESS_KEY_ID, secretAccessKey: config.S3_SECRET_ACCESS_KEY, prefix: config.S3_PREFIX,
    }, config.MAX_UPLOAD_BYTES, config.MAX_VIDEO_BYTES);
  }
  return new LocalStorage(config.STORAGE_DIR, config.MAX_UPLOAD_BYTES, config.MAX_VIDEO_BYTES);
}
